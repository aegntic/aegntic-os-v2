const { chromium } = require(process.env.AEGNTIC_PLAYWRIGHT_MODULE || "playwright");
const fs = require('node:fs');
const path = require('node:path');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1100}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const folder=path.resolve(__dirname, '../artifacts/product-foundry/first-run');
 await page.goto('http://127.0.0.1:4317/');await page.locator('.outcome').last().waitFor();
 if(await page.locator('.outcome').count()!==5)throw Error('Five outcome cards missing');
 await page.screenshot({path:path.join(folder,'workspace-desktop.png'),fullPage:true});
 const initial=Number(await page.locator('#count').innerText());
 await page.route('**/api/workspace',route=>route.abort());
 await page.locator('#title').fill('First run — persistent outcome workspace');
 await page.locator('#objective').fill('Verify local briefs, explicit connection readiness, and evidence-backed pre-launch records. This is a local test record.');
 await page.getByRole('button',{name:'Save outcome brief'}).click();
 await page.waitForFunction(n=>document.querySelector('#count').textContent===String(n),initial+1);
 await page.unroute('**/api/workspace');
 await page.getByRole('button',{name:'Open pre-launch review'}).first().click();
 const cards=page.locator('.control');
 await cards.nth(0).locator('select').selectOption('not-applicable');
 await cards.nth(0).locator('textarea').fill('Local-only brief workspace: no account collection. Operator test observation.');
 await cards.nth(1).locator('select').selectOption('pass');
 await cards.nth(1).locator('textarea').fill('Unsaved second-control draft must survive saving the first control.');
 await cards.nth(0).getByRole('button',{name:'Save review'}).click();
 await page.waitForFunction(()=>document.querySelector('#notice').textContent.includes('C1 review saved'));
 if(await cards.nth(1).locator('textarea').inputValue()!=='Unsaved second-control draft must survive saving the first control.')throw Error('Cross-control draft discarded');
 await page.reload();await page.locator('.outcome').last().waitFor();
 await page.getByRole('button',{name:'Open pre-launch review'}).first().click();
 if(!(await page.locator('.control').first().locator('textarea').inputValue()).includes('Local-only'))throw Error('Review persistence failed');
 await page.locator('#title').fill('Lost-response retry check');
 await page.locator('#objective').fill('The backend accepts the brief before the browser loses its response. Retry must reuse the same brief.');
 let intercepted=false;
 await page.route('**/api/projects',async route=>{if(!intercepted){intercepted=true;await route.fetch();await route.abort();}else await route.continue();});
 await page.getByRole('button',{name:'Save outcome brief'}).click();
 await page.waitForFunction(()=>!document.querySelector('#brief button').disabled);
 await page.getByRole('button',{name:'Save outcome brief'}).click();
 await page.waitForFunction(n=>document.querySelector('#count').textContent===String(n),initial+2);
 const data=await (await page.request.get('http://127.0.0.1:4317/api/workspace')).json();
 if(data.projects.length!==initial+2)throw Error('Lost-response retry created duplicate');
 await page.setViewportSize({width:390,height:844});await page.goto('http://127.0.0.1:4317/');await page.locator('.outcome').last().waitFor();
 if(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth))throw Error('Mobile horizontal overflow');
 await page.screenshot({path:path.join(folder,'workspace-mobile.png'),fullPage:true});
 if(errors.length)throw Error(errors.join(';'));
 const report={status:'PASS',checks:['five outcome cards','save works without post-create refresh','review draft survives another control save','review survives reload','lost-response retry does not duplicate','mobile has no horizontal overflow','no browser page errors'],screenshots:['workspace-desktop.png','workspace-mobile.png'],externalRequests:'none intentionally made; only loopback app requests',testRecordsCreated:2};
 fs.writeFileSync(path.join(folder,'browser-evidence.json'),JSON.stringify(report,null,2)+'\n');
 console.log(JSON.stringify(report));await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
